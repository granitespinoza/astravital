// Exports the seed-142 states computed by the real local database, so the browser web demo
// can run the same dialogue policy (server/assistant.mjs) without a server. Synthetic data only.
import {writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {createDatabase} from '../server/database.mjs';
import {ORIGIN} from '../app/scenarios.js';
import {SOL} from '../app/engine.js';

// Fixed simulation clock so repeated builds export identical bytes.
const db = createDatabase({path: ':memory:', seed: 142, clock: () => Date.UTC(2026, 10, 14, 7, 30)});
const base = {cardiovascular: db.getState('cardiovascular'), bone: db.getState('bone')};
const {seed, counts} = db.getEvidence();
const performed = db.repeatReading({scenario: base.cardiovascular.scenario}).state;
const visorEvidence = db.getEvidence();
const heart = db.requestReview({domain: 'cardiovascular', scenario: base.cardiovascular.scenario, confirmed: true, requestId: 'web-demo-heart'});
const bone = db.requestReview({domain: 'bone', scenario: base.bone.scenario, confirmed: true, requestId: 'web-demo-bone'});
db.close();

const snapshot = {
  generatedBy: 'scripts/export-demo.mjs',
  note: 'Synthetic seed-142 states computed by server/database.mjs for the browser web demo. Not NASA or patient data.',
  seed,
  simulated: true,
  states: {
    cardiovascular: {base: base.cardiovascular, performed, requested: heart.state},
    bone: {base: base.bone, requested: bone.state},
  },
  reviews: {cardiovascular: heart.review, bone: bone.review},
  evidence: {seed, counts},
};
const out = fileURLToPath(new URL('../app/demo-snapshot.json', import.meta.url));
writeFileSync(out, JSON.stringify(snapshot, null, 1) + '\n');
console.log(`Web demo snapshot: heart ${base.cardiovascular.scenario}/${base.cardiovascular.state}, bone ${base.bone.scenario}/${base.bone.state}.`);

function sharedCrewMember(member, heartState) {
  const {reading,decision,evidenceIds} = heartState;
  const silver = visorEvidence.silver.filter(row => evidenceIds.includes(row.id))
    .map(({id,bronzeId,observation}) => ({id,bronzeId,observation}));
  const bronze = visorEvidence.bronze.filter(row => silver.some(record => record.bronzeId === row.id))
    .map(({id,raw,source}) => ({id,raw,source}));
  const latestEvidenceId = silver.find(row => row.observation.id === reading.id).id;
  const initial = base.cardiovascular.reading;
  const samples = heartState.performed ? [initial,reading] : [reading];
  const receivedAt = new Date(reading.observedAt).toISOString();
  const history = [...heartState.history,...samples].filter(point => point.observedAt >= initial.observedAt - 13 * SOL);
  const timeline = samples.map(point => ({
    id:silver.find(row => row.observation.id === point.id).id,
    kind:'packet', at:new Date(point.observedAt).toISOString(),
    label:point.id === initial.id ? 'Initial resting check received onboard' : 'Repeat resting check received onboard',
  }));
  return {...member, reading, decision, evidenceIds, latestEvidenceId, receivedAt, history, timeline,
    repeated:heartState.performed, confirmedAlert:false,
    visorCase:heartState.performed ? 'repeat' : 'initial',
    evidence:{
      bronze:[...bronze,...member.evidence.bronze],
      silver:[...silver,...member.evidence.silver],
      gold:[{id:heartState.id,decision,evidenceIds},...member.evidence.gold],
    },
  };
}

// AI assistance: OpenAI Codex. Exercise the same mission ingest, acknowledgment and
// frozen-report path as the local console, using a reproducible simulation clock.
let moment = ORIGIN + 120000;
const missionDb = createDatabase({path: ':memory:', seed: 142, mission: true, clock:() => moment,
  reportId:() => 'mission-web-demo-weekly-142'});
try {
  const mission = missionDb.mission;
  const profiles = [
    ['crew-01',['steady','high','high']],
    ['crew-02',['steady']],
    ['crew-04',['steady']],
  ];
  let sequence = 0;
  for (const [crewId, samples] of profiles) {
    const {profiles: values} = mission.getCrew(crewId);
    for (const profile of samples) {
      moment += 60000;
      mission.ingest(crewId,{packetId:(++sequence).toString(16).padStart(32,'0'),value:values[profile],simulated:true});
    }
  }
  const {crewId,latestEvidenceId} = mission.getCrew('crew-01');
  moment += 60000;
  mission.acknowledge({crewId,evidenceId:latestEvidenceId,confirmed:true});
  const report = mission.queueReport({kind:'weekly'});
  moment = Date.parse(report.dueAt);
  const {reports} = mission.getGround();
  const trainingReport = reports[0];
  const alex = trainingReport.crew.find(member => member.crewId === base.cardiovascular.reading.crewId);
  const file = fileURLToPath(new URL('../app/mission-demo.json',import.meta.url));
  writeFileSync(file, JSON.stringify({generatedBy:'scripts/export-demo.mjs',seed:142,simulated:true,
    note:'AI assistance: OpenAI Codex. Synthetic records generated by the ASTRAVITAL engines.',
    reports:[{...trainingReport,crew:trainingReport.crew.map(member => member === alex
      ? sharedCrewMember(alex,base.cardiovascular) : member)}],
    sharedRepeat:sharedCrewMember(alex,performed),
  }) + '\n');
  console.log('Mission demo snapshot: seed-142 roster with the same initial and repeat checks used by the glasses.');
} finally {
  missionDb.close();
}
